"""Directories whose contents describe something other than this project's needs.

A virtual environment is the dangerous one: its ``site-packages`` imports every
transitive dependency of everything installed, which would turn one project's
scan into a mirror of somebody's whole machine.
"""

_MANIFEST_NAMES = frozenset({"pyproject.toml", "setup.cfg"})

