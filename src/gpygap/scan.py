"""Import names that differ from their distribution by more than punctuation.

Only the ones a normalization cannot reach. ``cocotb_bus`` is absent on purpose:
``cocotb-bus`` falls out of :func:`gpygap.util.normalize_name` already.
"""


class Source(StrEnum):
    """Where a requirement came from, which is how much it can be trusted."""

    DECLARED = "declared"
    """The project states it: a manifest or a requirements file."""
    MAPPED = "mapped"
    """An import whose distribution is in the table above."""
    GUESSED = "guessed"
    """An import whose distribution is its normalized name and nothing more."""


@dataclass(frozen=True, slots=True)
class Discovery:
    """One requirement and the file that asked for it."""

    requirement: str
    source: Source
    origin: str
    """Path of the file, relative to the scanned root, in POSIX form."""


@dataclass(frozen=True, slots=True)
class Unmatched:
    """An import that no distribution could be found for; a human has to decide."""

    module: str
    origins: tuple[str, ...]
    reason: str


@dataclass(frozen=True, slots=True)
class ScanResult:
    """Everything one scan of one directory found."""

    root: Path
    discoveries: tuple[Discovery, ...]
    unmatched: tuple[Unmatched, ...]
    lock_files: tuple[str, ...]
    """Lock files found in the tree; they belong in ``intake/`` unchanged."""
    python_files: int

    @property
    def requirements(self) -> tuple[str, ...]:
        """The requirement lines, de-duplicated, in the order they were discovered."""
        return tuple(dict.fromkeys(d.requirement for d in self.discoveries))


def scan_project(root: Path, *, follow_imports: bool = True, index_url: str | None = None) -> ScanResult:
    """Work out what the project at ``root`` needs from an index.

    ``index_url`` turns on confirmation of the guessed names: anything the index
    does not have becomes an :class:`Unmatched` entry rather than a requirement.
    """
    files = tuple(_files(root))
    manifests, locks = _manifests(root, files)
    discoveries = list(manifests)
    unmatched: list[Unmatched] = []
    python_files = tuple(f for f in files if f.suffix in (".py", ".pyi"))
    if follow_imports:
        found, unmatched = _from_imports(root, python_files, index_url)
        discoveries += found
    log.info(
        "Scan %s: %d requirements from %d Python files, %d unmatched imports",
        root,
        len({d.requirement for d in discoveries}),
        len(python_files),
        len(unmatched),
    )
    return ScanResult(
        root=root,
        discoveries=tuple(discoveries),
        unmatched=tuple(unmatched),
        lock_files=tuple(locks),
        python_files=len(python_files),
    )


def _files(root: Path) -> Iterator[Path]:
    """Every file below ``root``, with the noise directories and environments pruned."""
    if (root / "pyvenv.cfg").exists():
        log.debug("Scan skipping %s: it is a virtual environment", root)
        return
    try:
        entries = sorted(root.iterdir())
    except OSError as exc:
        log.warning("Scan cannot read %s: %s", root, exc)
        return
    for entry in entries:
        if entry.is_symlink():
            continue
        if entry.is_dir():
            if entry.name in _SKIP_DIRS or entry.name.endswith(".egg-info"):
                continue
            yield from _files(entry)
        elif entry.is_file():
            yield entry


def _manifests(root: Path, files: Iterable[Path]) -> tuple[list[Discovery], list[str]]:
    """Declared requirements, and the names of the lock files intake should be given."""
    discoveries: list[Discovery] = []
    locks: list[str] = []
    for path in files:
        origin = path.relative_to(root).as_posix()
        if _is_lock(path):
            locks.append(origin)
        elif path.name == "pyproject.toml":
            discoveries += _declared(_pyproject(path), origin)
        elif path.name == "setup.cfg":
            discoveries += _declared(_setup_cfg(path), origin)
        elif path.suffix == ".txt" and path.name.startswith("requirements"):
            discoveries += _declared(_requirements_file(path), origin)
    return discoveries, locks


def _is_lock(path: Path) -> bool:
    return path.suffix == ".lock" or (path.name.startswith("pylock") and path.suffix == ".toml")


def _declared(requirements: Iterable[str], origin: str) -> Iterator[Discovery]:
    for raw in requirements:
        if (requirement := _valid(raw, origin)) is not None:
            yield Discovery(requirement, Source.DECLARED, origin)


def _valid(raw: str, origin: str) -> str | None:
    """``raw`` as a PEP 508 requirement, or ``None`` if it is not one."""
    try:
        return str(Requirement(raw))
    except InvalidRequirement as exc:
        log.warning("Scan %s: %r is not a requirement (%s)", origin, raw, exc)
        return None


def _read_toml(path: Path) -> dict[str, Any]:
    try:
        parsed: dict[str, Any] = tomllib.loads(path.read_text("utf-8"))
        return parsed
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        log.warning("Scan %s skipped: %s", path, exc)
        return {}


def _pyproject(path: Path) -> Iterator[str]:
    """Dependencies declared in ``pyproject.toml``, under every standard key."""
    data = _read_toml(path)
    project = data.get("project", {})
    yield from _strings(project.get("dependencies"))
    for group in _tables(project.get("optional-dependencies")):
        yield from _strings(group)
    for group in _tables(data.get("dependency-groups")):
        yield from _strings(group)
    yield from _strings(data.get("build-system", {}).get("requires"))
    # Poetry's "^1.2" is not PEP 508, and rewriting it would be a guess about the
    # upper bound. The name is what decides whether the mirror has the project.
    poetry = data.get("tool", {}).get("poetry", {}).get("dependencies", {})
    if isinstance(poetry, dict):
        yield from (name for name in poetry if isinstance(name, str) and name.lower() != "python")


def _setup_cfg(path: Path) -> Iterator[str]:
    """``install_requires`` and ``extras_require`` of a setuptools configuration."""
    parser = configparser.ConfigParser()
    try:
        parser.read_string(path.read_text("utf-8"), source=str(path))
    except (OSError, UnicodeDecodeError, configparser.Error) as exc:
        log.warning("Scan %s skipped: %s", path, exc)
        return
    sections = [("options", "install_requires"), ("options", "setup_requires")]
    if parser.has_section("options.extras_require"):
        sections += [("options.extras_require", key) for key in parser["options.extras_require"]]
    for section, key in sections:
        for line in parser.get(section, key, fallback="").splitlines():
            if stripped := line.split("#", 1)[0].strip():
                yield stripped


def _requirements_file(path: Path) -> Iterator[str]:
    try:
        yield from requirement_lines(path.read_text("utf-8"))
    except (OSError, UnicodeDecodeError) as exc:
        log.warning("Scan %s skipped: %s", path, exc)


def _strings(value: Any) -> Iterator[str]:
    if isinstance(value, list):
        yield from (item for item in value if isinstance(item, str))


def _tables(value: Any) -> Iterator[Any]:
    if isinstance(value, dict):
        yield from value.values()


def _from_imports(
    root: Path, python_files: Iterable[Path], index_url: str | None
) -> tuple[list[Discovery], list[Unmatched]]:
    """Third-party imports of the tree, resolved to distributions where possible."""
    python_files = tuple(python_files)
    own = _own_modules(python_files)
    origins: dict[str, list[str]] = {}
    for path in python_files:
        origin = path.relative_to(root).as_posix()
        for module in sorted(_imports(path)):
            if module in own or module in sys.stdlib_module_names or module.startswith("_"):
                continue
            origins.setdefault(module, []).append(origin)
    discoveries: list[Discovery] = []
    unmatched: list[Unmatched] = []
    for module, where in origins.items():
        if (known := _DISTRIBUTIONS.get(module)) is not None:
            discoveries.append(Discovery(known, Source.MAPPED, where[0]))
        elif index_url is None or _on_index(module, index_url):
            discoveries.append(Discovery(normalize_name(module), Source.GUESSED, where[0]))
        else:
            unmatched.append(
                Unmatched(module, tuple(where), f"no project {normalize_name(module)!r} on the index")
            )
    return discoveries, unmatched


def _own_modules(python_files: Iterable[Path]) -> frozenset[str]:
    """Module names the tree provides itself, which must never become requirements.

    A testbench that does ``from commons import *`` is importing the file next to
    it; mirroring a PyPI project called ``commons`` would be worse than useless.
    """
    names: set[str] = set()
    for path in python_files:
        names.add(path.stem)
        if (path.parent / "__init__.py").exists():
            names.add(path.parent.name)
    return frozenset(names - {"__init__", "__main__"})


def _imports(path: Path) -> frozenset[str]:
    """Top-level module names imported anywhere in ``path``, relative imports aside."""
    try:
        tree = ast.parse(path.read_bytes(), filename=str(path))
    except (OSError, SyntaxError, ValueError) as exc:
        # A Python 2 script or a generated file is not worth failing a scan over;
        # it is reported at DEBUG because an unreadable file is a normal finding.
        log.debug("Scan %s not parsed: %s", path, exc)
        return frozenset()
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".", 1)[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
            names.add(node.module.split(".", 1)[0])
    return frozenset(names)


def _on_index(name: str, index_url: str) -> bool:
    """Whether the index has a project called ``name``.

    Unlike :func:`gpygap.util.http_get` this does not retry: a 404 is the answer,
    and retrying every wrong guess three times with backoff would make a scan of
    an unpackaged tree take minutes. A network failure is not an answer, so it
    keeps the requirement and says so -- dropping a real dependency because a
    proxy blinked is the one outcome a mirror cannot afford.
    """
    url = f"{index_url.rstrip('/')}/{normalize_name(name)}/"
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return 200 <= int(response.status) < 300
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return False
        log.warning("Scan cannot check %s on the index (HTTP %s); keeping it", name, exc.code)
    except OSError as exc:
        log.warning("Scan cannot check %s on the index (%s); keeping it", name, exc)
    return True


def render_requirements(result: ScanResult, *, today: date | None = None) -> str:
    """The scan as a requirements file for ``intake/``, with its provenance in comments.

    The comments matter more than the lines: an operator reading this file a month
    later needs to know which entries a human declared and which a parser guessed.
    """
    by_requirement = {d.requirement: d for d in reversed(result.discoveries)}
    ordered = sorted(by_requirement.values(), key=lambda d: normalize_name(d.requirement))
    width = max((len(d.requirement) for d in ordered), default=0)
    lines = [
        f"{GENERATED_HEADER} from {result.root} on {today or date.today()}.",
        "#",
        f"# {len(ordered)} requirements, out of {result.python_files} Python files. Review before",
        "# the next sync: an import name is not always a distribution name, and a line",
        "# marked 'guessed' is this tool's normalization of one, nothing stronger.",
    ]
    if result.lock_files:
        lines += [
            "#",
            "# The project also carries lock files. Copy them into the intake directory",
            "# unchanged rather than trusting the lines below for those packages:",
            *(f"#   {path}" for path in result.lock_files),
        ]
    if result.unmatched:
        lines += [
            "#",
            "# Imports no distribution was found for. Each one is either a module of the",
            "# project that this scan could not see, or a package that needs a name here:",
            *(
                f"#   {item.module} ({', '.join(item.origins[:3])}): {item.reason}"
                for item in result.unmatched
            ),
        ]
    lines.append("")
    lines += [f"{d.requirement.ljust(width)}  # {d.source}, {d.origin}" for d in ordered]
    return "\n".join(lines) + "\n"
