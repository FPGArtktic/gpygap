"""What a project needs, worked out from the project's own directory.

``intake/`` answers "mirror exactly what this lock file pins". This module
answers the question that comes before it: somebody hands over a directory that
was never packaged -- a simulation harness, a pile of scripts, a vendor drop --
and a human has to say which distributions it will not start without. Doing that
by eye is how a mirror ends up one package short, and the person who finds out is
the one with no way to download it.

Two sources, in descending order of trust:

* **Declared dependencies**: ``pyproject.toml`` (PEP 621 dependencies, optional
  dependencies, PEP 735 groups, build requirements), ``setup.cfg`` and
  ``requirements*.txt``. Taken at their word, version specifiers included.
* **Imports**: every ``.py`` file is parsed with :mod:`ast`; what survives
  dropping the standard library and the modules the tree provides itself must
  come from an index. An import name is not a distribution name
  (``cocotb_bus`` is ``cocotb-bus``, ``yaml`` is ``PyYAML``), so a table of the
  known mismatches is consulted first and a PEP 503 normalization second.

Lock files are reported, never flattened: ``intake/`` reads ``uv.lock`` and
``pylock*.toml`` natively and exactly, and a scan that rewrote them into loose
requirements would throw away the pinning that made them worth having.

Because a guess is a liability in a mirror nobody can patch from the inside, the
guessed names can be confirmed against the configured index; whatever it does not
know is reported for a human instead of being written as a requirement.
"""

from __future__ import annotations

import ast
import configparser
import logging
import sys
import tomllib
import urllib.error
import urllib.request
from collections.abc import Iterable, Iterator, Mapping
